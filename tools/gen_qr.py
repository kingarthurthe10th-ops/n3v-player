# Writes source/qr.h: the QR code for the GitHub releases page, shown on the 3DS's first-launch notice.
import qrcode
URL = 'https://github.com/kingarthurthe10th-ops/n3v-player/releases/latest'
q = qrcode.QRCode(border=0, error_correction=qrcode.constants.ERROR_CORRECT_M); q.add_data(URL); q.make(fit=True)
m = q.get_matrix(); n = len(m)
rows = ',\n'.join('\t"%s"' % ''.join('#' if c else '.' for c in r) for r in m)
open('source/qr.h', 'w').write('// generated by tools/gen_qr.py: %s\n#define QR_N %d\nstatic const char *const QR_ROWS[QR_N] = {\n%s\n};\n' % (URL, n, rows))
print('QR', n, 'x', n)
